def resolve_benchmark_components(
    args: argparse.Namespace,
) -> None:
    """
    Resolve semantic specification and evaluator paths.

    Priority:
      1. Explicit --spec or --evaluator override
      2. Paths registered for --benchmark
    """

    config = None

    if args.benchmark is not None:
        config = get_benchmark_config(args.benchmark)

    if args.spec is None:
        if config is None:
            raise ValueError("Either --benchmark or --spec must be provided.")

        args.spec = config.spec_path

    if args.evaluator is None:
        if config is None:
            raise ValueError("Either --benchmark or --evaluator must be provided.")

        args.evaluator = config.evaluator_path

    args.spec = args.spec.expanduser().resolve()
    args.evaluator = args.evaluator.expanduser().resolve()

    if not args.spec.is_file():
        raise FileNotFoundError(
            f"Semantic specification does not exist: " f"{args.spec}"
        )

    if not args.evaluator.is_file():
        raise FileNotFoundError(
            f"Semantic evaluator does not exist: " f"{args.evaluator}"
        )


