#!/usr/bin/env python3
"""
run_batch_semantic_validation.py

Batch semantic-validation orchestrator.

Pipeline for each syntactically valid candidate:

    candidate.rebeca
        -> RMC code generation
        -> compile generated C++ model checker
        -> execute model checker
        -> produce XML result
        -> execute benchmark-specific evaluator
        -> store detailed semantic result

The runner is benchmark-independent. Benchmark-specific logic belongs in
separate evaluator scripts.

A failure in one candidate does not stop the remaining batch.
"""

